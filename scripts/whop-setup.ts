// Creates one Whop one-time variant per catalogue item and writes src/lib/weechat/whop-variants.ts.
// Run: bun scripts/whop-setup.ts  (needs WHOP_API_KEY, WHOP_COMPANY_ID). Re-runs reuse existing ids.
import { paydunyaCatalogue } from '../src/lib/weechat/paydunya-catalog';
import { whopVariants, whopProductId } from '../src/lib/weechat/whop-variants';
const H = { Authorization: `Bearer ${process.env['WHOP_API_KEY']}`, 'Content-Type': 'application/json' };
const acc = process.env['WHOP_COMPANY_ID'];
const api = async (p: string, b: unknown) => { const r = await fetch(`https://api.whop.com/api/v1/${p}`, { method: 'POST', headers: H, body: JSON.stringify(b) }); const j = await r.json(); if (!r.ok) throw new Error(`${p}: ${JSON.stringify(j)}`); return j as { id: string }; };
const product = whopProductId || (await api('products', { account_id: acc, title: 'Weechat' })).id;
const map: Record<string, string> = { ...whopVariants };
for (const i of paydunyaCatalogue) {
  if (map[i.id] || !(i.amountUSD > 0)) continue;
  map[i.id] = (await api('variants', { account_id: acc, product_id: product, billing_type: 'one_time', initial_price: i.amountUSD, currency: 'usd', title: i.label })).id;
  console.log(i.id, '->', map[i.id], i.amountUSD);
}
await Bun.write('src/lib/weechat/whop-variants.ts', `// Generated by scripts/whop-setup.ts — Whop one-time variant per catalogue item.\nexport const whopProductId = ${JSON.stringify(product)};\nexport const whopVariants: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`);
